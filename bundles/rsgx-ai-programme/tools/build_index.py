#!/usr/bin/env python3
"""Regenerate a bundle's root index.md from its concepts' frontmatter: python build_index.py <bundle-dir>

OKF v0.2 makes index.md a reserved file: at the bundle root its frontmatter is exactly
{okf_version}, and it lists the concepts. This script writes that one file, listing every
non-reserved .md concept grouped by its top-level folder, each with its title, type, status
and provenance marker. It reads frontmatter only and never edits a concept.

Deterministic on purpose: no timestamps, sorted paths, LF endings. CI re-runs it and fails when
the committed index.md differs, so run it after adding, renaming or retitling a concept and
commit the result. Folders follow the README's layout order; any other folder comes after,
alphabetically. Written 14/10/2026 from the OKF v0.2 rules and the format rsgx-okf-indexer
renders, because no build_index.py exists in rsgx-org-ai/rsgx-okf or elsewhere in the org.

Exit status: 0 on success (whether or not the file changed), 2 on bad arguments.
"""
import sys
from pathlib import Path

import yaml

RESERVED = {"index.md", "log.md"}
SKIP_DIRS = {"tools", "__pycache__"}
FOLDER_ORDER = ["", "handoff", "decisions", "open-questions", "findings", "assessments", "specs",
                "prototypes", "references"]
FOLDER_TITLES = {"": "Bundle", "handoff": "Handoff", "decisions": "Decisions",
                 "open-questions": "Open questions", "findings": "Findings", "assessments": "Assessments",
                 "specs": "Specs", "prototypes": "Prototypes", "references": "References"}


def frontmatter(path):
    text = path.read_text(encoding="utf-8").replace("\r\n", "\n")
    if not text.startswith("---\n"):
        return {}
    end = text.find("\n---", 3)
    if end == -1:
        return {}
    try:
        data = yaml.safe_load(text[4:end])
    except yaml.YAMLError:
        return {}
    return data if isinstance(data, dict) else {}


def one_line(value):
    return " ".join(str(value).split()).replace("[", "(").replace("]", ")")


def entry(root, path):
    rel = path.relative_to(root).as_posix()
    data = frontmatter(path)
    title = one_line(data.get("title") or path.stem)
    facts = [one_line(data[k]) for k in ("type", "status") if data.get(k)]
    if data.get("provenance"):
        facts.append("[" + one_line(data["provenance"]) + "]")
    tail = " · " + " · ".join(facts) if facts else ""
    return f"- [{title}]({rel}){tail}"


def build(root):
    groups = {}
    for path in sorted(root.rglob("*.md")):
        rel = path.relative_to(root)
        if path.name in RESERVED or any(part in SKIP_DIRS or part.startswith(".") for part in rel.parts[:-1]):
            continue
        folder = rel.parts[0] if len(rel.parts) > 1 else ""
        groups.setdefault(folder, []).append(entry(root, path))
    order = [f for f in FOLDER_ORDER if f in groups] + sorted(f for f in groups if f not in FOLDER_ORDER)
    lines = ["---", 'okf_version: "0.2"', "---", "", f"# {root.name}", "",
             "Generated by `tools/build_index.py` from each concept's frontmatter. Do not edit by hand: "
             "re-run the script and commit the result.", "", "# Contents"]
    for folder in order:
        lines += ["", f"## {FOLDER_TITLES.get(folder, folder)}", ""] + groups[folder]
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) != 2:
        print("usage: python build_index.py <bundle-dir>")
        return 2
    root = Path(argv[1]).resolve()
    target = root / "index.md"
    new = build(root)
    old = target.read_text(encoding="utf-8") if target.exists() else None
    if new != old:
        target.write_text(new, encoding="utf-8", newline="\n")
        print(f"wrote {target}")
    else:
        print(f"{target} is up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
